import { test, expect } from "@playwright/test";
import { eq, sql } from "drizzle-orm";
import { db, pool } from "@/db";
import { orders, otpChallenges, products, users } from "@/db/schema";

const phones: string[] = [];
let usedChallenge = "";
let usedCode = "";
const newPhone = () => `+919${Date.now().toString().slice(-9)}`;

test.afterAll(async () => {
  for (const phone of phones) {
    const [user] = await db.select().from(users).where(eq(users.phone, phone));
    if (user) {
      const placed = await db.select().from(orders).where(eq(orders.userId, user.id));
      for (const order of placed) for (const item of order.items) if (item.productId.startsWith("sv-")) await db.update(products).set({ stock: sql`${products.stock} + ${item.quantity}` }).where(eq(products.id, item.productId));
      await db.delete(orders).where(eq(orders.userId, user.id));
      await db.delete(products).where(eq(products.sellerId, user.id));
      await db.delete(users).where(eq(users.id, user.id));
    }
    await db.delete(otpChallenges).where(eq(otpChallenges.phone, phone));
  }
  await pool.end();
});

