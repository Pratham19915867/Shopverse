test("authentication rejects invalid, replayed, rate-limited and exhausted codes", async ({ request }) => {
  expect((await request.post("/api/products", { data: {} })).status()).toBe(401);
  expect((await request.post("/api/account", { data: {} })).status()).toBe(405);
  expect((await request.patch("/api/account", { data: {} })).status()).toBe(401);
  expect((await request.post("/api/auth/request", { data: { phone: "invalid" } })).status()).toBe(400);
  expect((await request.post("/api/auth/verify", { data: { challengeId: usedChallenge, code: usedCode } })).status()).toBe(400);
  const phone = newPhone(); phones.push(phone);
  const challenge = await (await request.post("/api/auth/request", { data: { phone } })).json();
  expect(challenge.demo).toBe(true);
  expect((await request.post("/api/auth/request", { data: { phone } })).status()).toBe(429);
  for (let index = 0; index < 5; index++) expect((await request.post("/api/auth/verify", { data: { challengeId: challenge.challengeId, code: "000000" } })).status()).toBe(400);
  const blocked = await request.post("/api/auth/verify", { data: { challengeId: challenge.challengeId, code: challenge.demoCode } });
  expect(blocked.status()).toBe(400);
  expect((await blocked.json()).error).toContain("attempt limit");
});
